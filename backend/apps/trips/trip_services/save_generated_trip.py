def parse_duration_minutes(duration):
    """
    Convert a duration string such as:

        2h 30m
        2h
        45m

    into total minutes.
    """

    if duration is None:
        return 0

    # Already numeric
    if isinstance(
        duration,
        (int, float),
    ):
        return int(duration)

    duration = str(
        duration
    ).strip().lower()

    hours = 0
    minutes = 0

    # ------------------------------------------------------
    # HOURS
    # ------------------------------------------------------

    if "h" in duration:

        hours_part = (
            duration
            .split("h")[0]
            .strip()
        )

        if hours_part:
            hours = int(
                hours_part
            )

    # ------------------------------------------------------
    # MINUTES
    # ------------------------------------------------------

    if "m" in duration:

        if "h" in duration:

            minutes_part = (
                duration
                .split("h", 1)[1]
                .replace("m", "")
                .strip()
            )

        else:

            minutes_part = (
                duration
                .replace("m", "")
                .strip()
            )

        if minutes_part:
            minutes = int(
                minutes_part
            )

    return (
        hours * 60
        + minutes
    )


def parse_datetime(value):
    """
    Parse an ISO datetime generated by FlightGenerator.

    Example:

        2026-08-20T08:30:00+05:30
    """

    if isinstance(
        value,
        datetime,
    ):
        return value

    return datetime.fromisoformat(
        str(value)
    )


